export const ENV_HEADER = "# Generated by nocollide.";

const ASSIGNMENT = /^(\s*(?:export\s+)?)([A-Za-z_][A-Za-z0-9_]*)(\s*=)/;
const PLACEHOLDER = /\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g;

export function isGenerated(content: string): boolean {
  return content.startsWith(ENV_HEADER);
}

export function renderEnv(template: string, vars: Record<string, string>, slot: number): string {
  const filled = template.replace(PLACEHOLDER, (match, name: string) => vars[name] ?? match);
  const seen = new Set<string>();
  const lines = filled
    .split(/\r?\n/)
    .filter((line, index) => !(index === 0 && isGenerated(line)))
    .map((line) => {
      const match = ASSIGNMENT.exec(line);
      const name = match?.[2];
      if (!match || !name || vars[name] === undefined) return line;
      seen.add(name);
      return `${match[1]}${name}${match[3]}${vars[name]}`;
    });
  while (lines.length > 0 && lines[lines.length - 1]!.trim() === "") lines.pop();
  for (const [name, value] of Object.entries(vars)) {
    if (!seen.has(name)) lines.push(`${name}=${value}`);
  }
  const header = `${ENV_HEADER} Slot ${slot}. Run "nocollide up" to regenerate; manual edits are overwritten.`;
  return `${[header, ...lines].join("\n")}\n`;
}
