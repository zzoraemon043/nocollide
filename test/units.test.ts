import assert from "node:assert/strict";
import { test } from "node:test";
import { parseConfig } from "../src/config.js";
import { slotPorts, slotVars } from "../src/core.js";
import { isGenerated, renderEnv } from "../src/env.js";

test("parseConfig applies the default step and keeps env", () => {
  const config = parseConfig({ ports: { WEB_PORT: 3000 }, env: { from: ".env.example", to: ".env.local" } });
  assert.deepEqual(config, { ports: { WEB_PORT: 3000 }, step: 10, env: { from: ".env.example", to: ".env.local" } });
});

test("parseConfig rejects bad input with a readable message", () => {
  assert.throws(() => parseConfig({ ports: {} }), /at least one/);
  assert.throws(() => parseConfig({ ports: { web: 3000 } }), /upper-case/);
  assert.throws(() => parseConfig({ ports: { WEB_PORT: 70000 } }), /between 1 and 65535/);
  assert.throws(() => parseConfig({ ports: { WEB_PORT: 3000 }, step: 0 }), /positive integer/);
  assert.throws(() => parseConfig({ ports: { WEB_PORT: 3000 }, env: { from: ".env" } }), /"env" must/);
});

test("slot ports are base plus slot times step", () => {
  const config = parseConfig({ ports: { WEB_PORT: 3000, API_PORT: 4000 }, step: 10 });
  assert.deepEqual(slotPorts(config, 0), { WEB_PORT: 3000, API_PORT: 4000 });
  assert.deepEqual(slotPorts(config, 3), { WEB_PORT: 3030, API_PORT: 4030 });
  assert.deepEqual(slotVars(slotPorts(config, 2), 2), { WEB_PORT: "3020", API_PORT: "4020", NOCOLLIDE_SLOT: "2" });
});

test("renderEnv fills placeholders, overrides keys and appends missing ones", () => {
  const template = [
    "# app settings",
    "WEB_PORT=3000",
    "export API_PORT = 4000",
    "DATABASE_URL=postgres://localhost/app_s${NOCOLLIDE_SLOT}",
    "PUBLIC_URL=http://localhost:${WEB_PORT}",
    "UNKNOWN=${NOT_A_SLOT_VAR}",
    "",
  ].join("\n");
  const output = renderEnv(template, { WEB_PORT: "3010", API_PORT: "4010", NOCOLLIDE_SLOT: "1" }, 1);
  assert.ok(isGenerated(output));
  assert.equal(
    output.split("\n").slice(1).join("\n"),
    [
      "# app settings",
      "WEB_PORT=3010",
      "export API_PORT =4010",
      "DATABASE_URL=postgres://localhost/app_s1",
      "PUBLIC_URL=http://localhost:3010",
      "UNKNOWN=${NOT_A_SLOT_VAR}",
      "NOCOLLIDE_SLOT=1",
      "",
    ].join("\n"),
  );
});

test("renderEnv drops an old header so it never stacks", () => {
  const once = renderEnv("A=1\n", { WEB_PORT: "3000" }, 0);
  const twice = renderEnv(once, { WEB_PORT: "3010" }, 1);
  assert.equal(twice.match(/Generated by nocollide/g)?.length, 1);
  assert.match(twice, /WEB_PORT=3010/);
});
