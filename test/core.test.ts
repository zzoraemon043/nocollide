import assert from "node:assert/strict";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createServer, type Server } from "node:net";
import { join } from "node:path";
import { test } from "node:test";
import { down, gc, init, list, up } from "../src/core.js";
import { addWorktree, config, randomBase, removeWorktree, sandbox } from "./helpers.js";

function listen(port: number): Promise<Server> {
  return new Promise((resolve, reject) => {
    const server = createServer();
    server.once("error", reject);
    server.listen(port, () => resolve(server));
  });
}

test("main worktree gets slot 0 and other worktrees get the next free slots", async (t) => {
  const base = randomBase();
  const box = sandbox({ "nocollide.json": config({ WEB_PORT: base }), ".env.example": "WEB_PORT=1\n" });
  t.after(box.cleanup);
  const a = addWorktree(box, "feat-a");
  const b = addWorktree(box, "feat-b");

  assert.equal((await up(box.repo)).slot, 0);
  const claimA = await up(a);
  const claimB = await up(b);
  assert.equal(claimA.slot, 1);
  assert.equal(claimB.slot, 2);
  assert.deepEqual(claimB.ports, { WEB_PORT: base + 20 });

  const again = await up(a);
  assert.equal(again.slot, 1);
  assert.equal(again.created, false);

  const env = readFileSync(join(b, ".env.local"), "utf8");
  assert.match(env, new RegExp(`^WEB_PORT=${base + 20}$`, "m"));
  assert.match(env, /^NOCOLLIDE_SLOT=2$/m);
});

test("a slot whose port is already listening is skipped", async (t) => {
  const base = randomBase();
  const box = sandbox({ "nocollide.json": config({ WEB_PORT: base }) });
  t.after(box.cleanup);
  const server = await listen(base + 10);
  t.after(() => server.close());
  const claim = await up(addWorktree(box, "busy"));
  assert.equal(claim.slot, 2);
});

test("down frees the slot and removes the generated env file", async (t) => {
  const base = randomBase();
  const box = sandbox({ "nocollide.json": config({ WEB_PORT: base }) });
  t.after(box.cleanup);
  const a = addWorktree(box, "a");
  const b = addWorktree(box, "b");
  await up(a);
  await up(b);
  const result = await down(a);
  assert.equal(result.slot, 1);
  assert.equal(existsSync(join(a, ".env.local")), false);
  const c = addWorktree(box, "c");
  assert.equal((await up(c)).slot, 1);
  assert.deepEqual(await down(a), {});
});

test("an env file that nocollide did not write is never overwritten without force", async (t) => {
  const box = sandbox({ "nocollide.json": config({ WEB_PORT: randomBase() }) });
  t.after(box.cleanup);
  const a = addWorktree(box, "a");
  writeFileSync(join(a, ".env.local"), "MINE=1\n");
  await assert.rejects(up(a), /not written by nocollide/);
  assert.deepEqual(await list(a), []);
  assert.equal(readFileSync(join(a, ".env.local"), "utf8"), "MINE=1\n");
  const forced = await up(a, { force: true });
  assert.equal(forced.slot, 1);
  assert.match(readFileSync(join(a, ".env.local"), "utf8"), /Generated by nocollide/);
});

test("ls lists slots and gc releases deleted worktrees", async (t) => {
  const box = sandbox({ "nocollide.json": config({ WEB_PORT: randomBase() }) });
  t.after(box.cleanup);
  const a = addWorktree(box, "a");
  const b = addWorktree(box, "b");
  await up(box.repo);
  await up(a);
  await up(b);
  removeWorktree(box, a);

  const rows = await list(b);
  assert.deepEqual(
    rows.map((row) => [row.slot, row.current, row.exists]),
    [
      [0, false, true],
      [1, false, false],
      [2, true, true],
    ],
  );
  const removed = await gc();
  assert.deepEqual(
    removed.map((entry) => entry.slot),
    [1],
  );
  assert.equal((await list(b)).length, 2);
});

test("init writes a config from detected ports and refuses to overwrite it", async (t) => {
  const box = sandbox({ ".env.example": "API_PORT=4000\n" });
  t.after(box.cleanup);
  const result = init(box.repo);
  assert.deepEqual(JSON.parse(readFileSync(result.file, "utf8")), {
    ports: { API_PORT: 4000 },
    step: 10,
    env: { from: ".env.example", to: ".env.local" },
  });
  assert.throws(() => init(box.repo), /already exists/);
  init(box.repo, { force: true });
});

test("a worktree without its own config uses the main worktree config and template", async (t) => {
  const base = randomBase();
  const box = sandbox();
  t.after(box.cleanup);
  const worktree = addWorktree(box, "early");
  writeFileSync(join(box.repo, "nocollide.json"), config({ WEB_PORT: base }));
  writeFileSync(join(box.repo, ".env.example"), "WEB_PORT=1\nAPP=demo\n");
  const claim = await up(worktree);
  assert.equal(claim.slot, 1);
  const env = readFileSync(join(worktree, ".env.local"), "utf8");
  assert.match(env, /^APP=demo$/m);
  assert.match(env, new RegExp(`^WEB_PORT=${base + 10}$`, "m"));
  assert.equal((await down(worktree)).removedEnv, join(worktree, ".env.local"));
});

test("up without a config explains what to do", async (t) => {
  const box = sandbox();
  t.after(box.cleanup);
  await assert.rejects(up(box.repo), /Run "nocollide init" first/);
});
